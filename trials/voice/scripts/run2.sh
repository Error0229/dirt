#!/usr/bin/env bash
# The second measurement: reading a finished recording.
#
#   bash scripts/run2.sh NAME [NAME ...]     measure these models
#   bash scripts/run2.sh list                the names
#
# For every model: fetch it, time it on the 5, 15 and 60 second clips
# (three readings each), read the whole test set once for its mistakes,
# write down its size and its licence file, and delete it again, because
# the disk is short. Results go to data/results2. Two copies of this script
# can run side by side on different models: a copy that is timing makes the
# other wait (`--turn`), so that timings are not disturbed by the trial's
# own work.
#
# SET=data/set2/manifest-third.tsv reads only that manifest (made by
# scripts/third.py) for the models too slow to read the whole set. A timing
# already written is not taken again, and a reading that was cut off goes
# on from where it stopped.
#
# Three other modes, for after the queues:
#   MODE=fetch  bash scripts/run2.sh NAME...   fetch and keep, measure nothing
#   MODE=retime bash scripts/run2.sh NAME...   time again, into results2/retime
#   MODE=long   bash scripts/run2.sh NAME...   read data/long (ten minutes)
#               three times, into results2/long; LONG_WINDOW=25 cuts it
#               at pauses even for whisper.cpp, which otherwise reads it
#               whole with its own 30 second steps
# They keep the model when KEEP=1.
#
# Do not edit this file while it runs: copy it to data/run and run the copy.
set -u
here="$(cd "$(dirname "$0")" && pwd)"
case "$here" in */data/run) cd "$here/../.." ;; *) cd "$here/.." ;; esac
bin=./data/bin/voice-trial.exe
out=data/results2
models=data/models2
turn=data/turn
vad=$models/silero_vad.onnx
set=${SET:-data/set2/manifest.tsv}
mode=${MODE:-}
mkdir -p "$out/retime" "$out/long"
mkdir -p "$out" "$models" data/logs
gh=https://github.com/k2-fsa/sherpa-onnx/releases/download/asr-models

fetch() { # url, file
  [ -s "$2" ] && return
  curl -sSL --retry 8 --retry-delay 10 --retry-all-errors -A "voice-trial" -o "$2.part" "$1" && mv "$2.part" "$2"
}

# name | engine | kind | where from | what to read it with | window for cutting a long recording
# engine "cpp" is whisper.cpp reading a ggml file; "sherpa" is sherpa-onnx
# reading a folder from its asr-models release. A window of 0 hands the
# recording over whole.
entries="
cpp-base.en|cpp||ggerganov/whisper.cpp/ggml-base.en.bin||0
cpp-base.en-q5|cpp||ggerganov/whisper.cpp/ggml-base.en-q5_1.bin||0
cpp-small.en|cpp||ggerganov/whisper.cpp/ggml-small.en.bin||0
cpp-small.en-q5|cpp||ggerganov/whisper.cpp/ggml-small.en-q5_1.bin||0
cpp-distil-small.en|cpp||distil-whisper/distil-small.en/ggml-distil-small.en.bin||0
cpp-medium.en|cpp||ggerganov/whisper.cpp/ggml-medium.en.bin||0
cpp-medium.en-q5|cpp||ggerganov/whisper.cpp/ggml-medium.en-q5_0.bin||0
cpp-turbo|cpp||ggerganov/whisper.cpp/ggml-large-v3-turbo.bin||0
cpp-turbo-q5|cpp||ggerganov/whisper.cpp/ggml-large-v3-turbo-q5_0.bin||0
cpp-distil-large-v3|cpp||distil-whisper/distil-large-v3-ggml/ggml-distil-large-v3.bin||0
moonshine-tiny|sherpa|moonshine|sherpa-onnx-moonshine-tiny-en-quantized-2026-02-27||25
moonshine-base|sherpa|moonshine|sherpa-onnx-moonshine-base-en-quantized-2026-02-27||25
parakeet-110m|sherpa|nemo-transducer|sherpa-onnx-nemo-parakeet_tdt_transducer_110m-en-36000-int8||25
canary-180m-flash|sherpa|canary|sherpa-onnx-nemo-canary-180m-flash-en-es-de-fr-int8||25
zipformer-gigaspeech|sherpa|transducer|sherpa-onnx-zipformer-gigaspeech-2023-12-12||25
parakeet-v2|sherpa|nemo-transducer|sherpa-onnx-nemo-parakeet-tdt-0.6b-v2-int8||25
parakeet-v3|sherpa|nemo-transducer|sherpa-onnx-nemo-parakeet-tdt-0.6b-v3-int8||25
parakeet-unified|sherpa|nemo-transducer|sherpa-onnx-nemo-parakeet-unified-en-0.6b-int8-non-streaming||25
parakeet-redux|sherpa|nemo-transducer|sherpa-onnx-nemo-parakeet-tdt-0.6b-redux-int8||25
parakeet-ultra|sherpa|nemo-transducer|sherpa-onnx-nemo-parakeet-tdt-0.6b-ultra-int8||25
sherpa-whisper-base.en|sherpa|whisper|sherpa-onnx-whisper-base.en||25
sherpa-whisper-base.en-fp32|sherpa|whisper|sherpa-onnx-whisper-base.en|--fp32|25
sherpa-whisper-small.en|sherpa|whisper|sherpa-onnx-whisper-small.en||25
sherpa-whisper-small.en-fp32|sherpa|whisper|sherpa-onnx-whisper-small.en|--fp32|25
sherpa-whisper-distil-small.en|sherpa|whisper|sherpa-onnx-whisper-distil-small.en||25
sherpa-whisper-turbo|sherpa|whisper|sherpa-onnx-whisper-turbo||25
sherpa-whisper-distil-large-v3|sherpa|whisper|sherpa-onnx-whisper-distil-large-v3||25
sherpa-whisper-distil-large-v3.5|sherpa|whisper|sherpa-onnx-whisper-distil-large-v3.5||25
sherpa-whisper-medium.en|sherpa|whisper|sherpa-onnx-whisper-medium.en||25
"

if [ "${1:-}" = "list" ] || [ $# -eq 0 ]; then
  echo "$entries" | cut -d'|' -f1 | grep .
  exit 0
fi

fetch "$gh/silero_vad.onnx" "$vad"

for name in "$@"; do
  line=$(echo "$entries" | grep "^$name|") || { echo "no model called $name"; continue; }
  IFS='|' read -r _ engine kind source extra window <<< "$line"
  [ -z "$mode" ] && [ -s "$out/$name.set.jsonl" ] && [ -s "$out/$name.timing.jsonl" ] && { echo "have $name"; continue; }
  echo "== $name  $(date +%T)"

  if [ "$engine" = "cpp" ]; then
    repo=$(dirname "$source"); file=$(basename "$source")
    path="$models/$name.bin"
    fetch "https://huggingface.co/$repo/resolve/main/$file" "$path" || { echo "could not fetch $name"; continue; }
    args="--engine whisper --model $path"
    keep="$path"
  else
    path="$models/$source"
    if [ ! -d "$path" ]; then
      fetch "$gh/$source.tar.bz2" "$models/$source.tar.bz2" || { echo "could not fetch $name"; continue; }
      tar -xjf "$models/$source.tar.bz2" -C "$models" && rm -f "$models/$source.tar.bz2"
    fi
    args="--engine sherpa --kind $kind --model $path $extra"
    keep=""
  fi
  ls -la "$path" > "$out/$name.files.txt" 2>&1
  [ -d "$path" ] && ls -laR "$path" > "$out/$name.files.txt" 2>&1
  for doc in LICENSE LICENSE.txt README.md; do
    [ -f "$path/$doc" ] && { echo "---- $doc"; head -c 3000 "$path/$doc"; echo; } >> "$out/$name.licence.txt"
  done

  [ "$mode" = "fetch" ] && { echo "fetched|$name|$args|$window"; continue; }

  cut=""
  [ -n "${LONG_WINDOW:-}" ] && [ "$mode" = "long" ] && window=$LONG_WINDOW
  [ "$window" != "0" ] && cut="--vad $vad --window $window"

  if [ "$mode" = "retime" ] || [ "$mode" = "long" ]; then
    if [ "$mode" = "retime" ]; then
      what=data/timing/manifest.tsv; to="$out/retime/$name.timing.jsonl"
    else
      what=data/long/manifest.tsv; to="$out/long/$name${LONG_WINDOW:+-cut$LONG_WINDOW}.jsonl"
    fi
    $bin read $args $cut --set $what --repeat 3 --threads 4 --high-priority         --turn $turn --timing --out "$to.part" 2> "data/logs/$name.$mode.err"       && mv "$to.part" "$to"
    rm -f $turn
    tail -3 "data/logs/$name.$mode.err" | cut -c1-110
    [ "${KEEP:-0}" = "0" ] && { if [ -n "$keep" ]; then rm -f "$keep"; else rm -rf "$models/$source"; fi; }
    continue
  fi

  if [ ! -s "$out/$name.timing.jsonl" ]; then
    $bin read $args $cut --set data/timing/manifest.tsv --repeat 3 --threads 4 --high-priority \
        --turn $turn --timing --out "$out/$name.timing.jsonl.part" 2> "data/logs/$name.timing.err" \
      && mv "$out/$name.timing.jsonl.part" "$out/$name.timing.jsonl"
    rm -f $turn
    tail -3 "data/logs/$name.timing.err" | cut -c1-110
  fi

  part="$out/$name.set.jsonl.part"
  if [ -s "$part" ]; then
    # Go on from where a cut-off reading stopped.
    left="$(dirname "$set")/left-$name.tsv"
    echo "   $(python -I scripts/remaining.py "$part" "$set" "$left") left of $name"
    $bin read $args $cut --set "$left" --threads 4 --high-priority \
        --turn $turn --out "$part.more" 2>> "data/logs/$name.set.err" \
      && cat "$part.more" >> "$part" && rm -f "$part.more" "$left" \
      && mv "$part" "$out/$name.set.jsonl"
  else
    $bin read $args $cut --set "$set" --threads 4 --high-priority \
        --turn $turn --out "$part" 2> "data/logs/$name.set.err" \
      && mv "$part" "$out/$name.set.jsonl"
  fi
  echo "   $name done $(date +%T): $(grep -c ' piece' "data/logs/$name.set.err") read"

  # Two entries may read the same folder (8-bit and 32-bit): it goes when
  # no later name on this command line needs it.
  later=0
  seen=0
  for other in "$@"; do
    [ "$seen" = "1" ] && echo "$entries" | grep "^$other|" | grep -q "|$source|" && later=1
    [ "$other" = "$name" ] && seen=1
  done
  if [ "$later" = "0" ] && [ "${KEEP:-0}" = "0" ]; then
    if [ -n "$keep" ]; then rm -f "$keep"; else rm -rf "$models/$source"; fi
  fi
done
echo "finished $(date +%T)"
